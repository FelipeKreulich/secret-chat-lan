#!/usr/bin/env node
/**
 * Build docs/commands.json from the code that actually implements the commands.
 *
 * The command list had drifted more than once — the README's table has been
 * short of the truth, and the website was advertising 66 and 63 when the real
 * counts were 67 and 64. The counts are not something anyone should be keeping
 * in their head: which commands exist is decided by the `case '/x':` labels in
 * the two controllers, and which ones work offline is decided by whether the
 * P2P controller has that label at all.
 *
 * So that is what this reads. The README and the command palette only supply
 * prose: grouping, argument shapes and descriptions. A command that exists in
 * neither is still emitted, with no summary, so the gap is visible instead of
 * silent.
 *
 * Run with `npm run commands:build`. `test/commands-json.test.js` regenerates
 * and compares, so a new command that never made it here fails CI.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (path) => readFileSync(join(root, path), 'utf8');

const OUTPUT = 'docs/commands.json';

/** Every `case '/x':` in a controller — the only authority on what exists. */
function implemented(source) {
  return new Set([...source.matchAll(/case '(\/[a-z-]+)':/g)].map((m) => m[1]));
}

/**
 * The README's command tables, which live inside one `<details>` block per
 * group. Each row is `| \`/cmd <args>\` | description |`, and a row may carry
 * more than one command when they belong together (`/kick` `/mute` `/ban`).
 */
function fromReadme(readme) {
  const section = readme.slice(
    readme.indexOf('## 💬 Commands'),
    readme.indexOf('### First run & config file'),
  );

  const prose = new Map();
  const order = [];

  for (const block of section.split('<details>').slice(1)) {
    const group = /<summary><b>(.+?)<\/b><\/summary>/.exec(block)?.[1];
    if (!group) continue;
    order.push(group);

    for (const line of block.split('\n')) {
      if (!line.startsWith('|')) continue;
      // Split on pipes the table means, not on the escaped ones inside a cell.
      const cells = line.split(/(?<!\\)\|/).slice(1, -1);
      if (cells.length < 2) continue;

      const [head, body] = cells.map((cell) => cell.trim());
      const names = [...head.matchAll(/`(\/[a-z-]+)([^`]*)`/g)];
      if (names.length === 0) continue;

      for (const [, name, args] of names) {
        prose.set(name, {
          group,
          // Only a row naming one command can be describing its arguments.
          args: names.length === 1 ? args.trim() : '',
          summary: body.replaceAll('\\|', '|'),
        });
      }
    }
  }

  return { prose, order };
}

/** The Ctrl+K palette: a one-liner for nearly everything, used as a fallback. */
function fromPalette(ui) {
  const block = ui.slice(ui.indexOf('const COMMAND_INFO'), ui.indexOf('];'));
  return new Map(
    [...block.matchAll(/\['(\/[a-z-]+)', *(?:'([^']*)'|"([^"]*)")\]/g)].map(
      (m) => [m[1], m[2] ?? m[3]],
    ),
  );
}

const relay = implemented(read('src/client/ChatController.js'));
const p2p = implemented(read('src/p2p/P2PChatController.js'));
const { prose, order } = fromReadme(read('README.md'));
const palette = fromPalette(read('src/client/UI.js'));

const OTHER = 'Other';
const groups = new Map([...order, OTHER].map((name) => [name, []]));

for (const name of [...new Set([...relay, ...p2p])].sort()) {
  const entry = prose.get(name);
  const group = entry?.group ?? OTHER;
  groups.get(group).push({
    name,
    args: entry?.args || '',
    summary: entry?.summary || palette.get(name) || '',
    modes: [relay.has(name) && 'relay', p2p.has(name) && 'p2p'].filter(Boolean),
  });
}

const payload = {
  $comment:
    'Generated by scripts/generate-commands.mjs — do not edit. Which commands exist comes from the case labels in the two controllers; prose comes from README.md and the Ctrl+K palette.',
  counts: {
    total: new Set([...relay, ...p2p]).size,
    relay: relay.size,
    p2p: p2p.size,
  },
  groups: [...groups]
    .filter(([, commands]) => commands.length > 0)
    .map(([name, commands]) => ({
      id: name.toLowerCase().replaceAll(/[^a-z0-9]+/g, '-'),
      name,
      commands,
    })),
};

const json = `${JSON.stringify(payload, null, 2)}\n`;

if (process.argv.includes('--check')) {
  if (read(OUTPUT) !== json) {
    console.error(`${OUTPUT} is out of date — run: npm run commands:build`);
    process.exit(1);
  }
} else {
  writeFileSync(join(root, OUTPUT), json);
  const missing = payload.groups
    .flatMap((g) => g.commands)
    .filter((c) => !c.summary);
  console.log(
    `${OUTPUT}: ${payload.counts.total} commands ` +
      `(${payload.counts.relay} relay, ${payload.counts.p2p} P2P)` +
      (missing.length ? `, ${missing.length} without a description` : ''),
  );
  for (const command of missing) console.log(`  no description: ${command.name}`);
}
